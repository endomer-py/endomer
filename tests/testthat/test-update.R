test_that("the offline catalog names every managed survey and its minimum", {
  mock_local()
  catalog<-endomer_packages();x<-endomer_deps()
  expect_identical(catalog$package,c("enftr","encftr","enhogar","engihr"))
  expect_identical(catalog$required,c("0.9.0","0.10.0","0.5.0","0.3.0"))
  expect_identical(x$package,catalog$package)
  expect_true(all(x$meets_requirement));expect_false(any(x$behind))
  expect_identical(x$status,rep("meets_minimum",4))
  expect_true(all(is.na(x$cran)));expect_true(all(is.na(x$loaded)))
  expect_identical(x$action,rep("none",4))
  expect_identical(x$source,rep("bundled_minimum",4))
  expect_identical(endomer_deps(),x)
})
