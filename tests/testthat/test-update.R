test_that("an index need not contain the metapackage or every survey", {
  mock_local()
  index<-data.frame(Package=c("enftr","encftr"),Version=c("0.9.0","0.11.0"))
  x<-endomer_deps(available=index)
  expect_identical(x$package,c("enftr","encftr","enhogar","engihr"))
  expect_identical(x$status,c("current","update_available","unavailable","unavailable"))
  expect_identical(x$behind,c(FALSE,TRUE,NA,NA))
  expect_identical(x$action,c("none","update","resolve_source","resolve_source"))
  expect_identical(x$target,x$cran)
  expect_identical(x$source,rep("supplied_index",4))
  empty<-index[0,];y<-endomer_deps(available=empty)
  expect_true(all(is.na(y$behind)));expect_identical(y$status,rep("unavailable",4))
})
