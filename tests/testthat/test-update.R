test_that("recursive reports follow mandatory graph edges and terminate cycles", {
  db<-fixture();db$Imports<-c("extA, stats",NA,NA,NA)
  extra<-.endomer_index(data.frame(Package=c("extA","extB","stats"),Version=c("1.0","2.0","4.5.1"),
    Imports=c("extB, missingDep","extA",NA),Priority=c(NA,NA,"base")))
  db<-rbind(db,extra[names(db)]);db$Suggests<-"optionalOnly"
  mock_local(db)
  x<-endomer_deps(recursive=TRUE)
  expect_setequal(x$package,c("enftr","encftr","enhogar","engihr","extA","extB","missingDep"))
  expect_false(any(c("R","stats","optionalOnly") %in% x$package))
  expect_true(all(is.na(x$required[x$package %in% c("extA","extB")])) )
  expect_true(all(x$status[x$package %in% c("extA","extB")]=="installed_unchecked"))
  expect_identical(x$action[x$package=="missingDep"],"resolve_source")
  index<-fixture();index$Imports<-c("newDep",NA,NA,NA)
  y<-endomer_deps(recursive=TRUE,available=index)
  expect_true("newDep" %in% y$package);expect_false("extA" %in% y$package)
})
test_that("invalid requests and malformed indices fail clearly", {
  mock_local()
  for(v in list(NA,1,"TRUE",c(TRUE,FALSE))) {
    expect_error(endomer_deps(recursive=v),"recursive")
    expect_error(endomer_update(quiet=v),"quiet")
  }
  for(v in list(NA,1,"@CRAN@",character(),"")) expect_error(endomer_deps(repos=v),"repos")
  expect_error(endomer_deps(repos="https://example.invalid",available=fixture()),"not both")
  expect_error(endomer_deps(available=list()),"available")
  expect_error(endomer_deps(available=data.frame(Package="enftr")),"Version")
  for(v in c(NA,"","1.x","v1.0"))
    expect_error(endomer_deps(available=data.frame(Package="enftr",Version=v)),"Version")
  expect_error(endomer_deps(available=rbind(fixture(),fixture())),"unique")
  expect_error(endomer_deps(lib.loc=NA_character_),"lib.loc")
})
